#!/usr/bin/env python3
"""
Write src/content/nist171.ts: NIST SP 800-171 Rev. 2 requirement text and Rev. 3
requirement titles, from NIST's own machine-readable releases (U.S. government
works, public domain).

Usage:
  python3 scripts/nist171-import.py <rev2-cprt.json> <rev3-oscal-catalog.json>

Sources:
  Rev. 2: NIST CPRT export of SP 800-171 Rev. 2 (csrc.nist.gov, "Export" on the
          SP 800-171 Rev. 2 page in the Cybersecurity and Privacy Reference Tool).
  Rev. 3: usnistgov/oscal-content, nist.gov/SP800-171/rev3/json/NIST_SP800-171_rev3_catalog.json
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    r2 = json.load(open(sys.argv[1], encoding="utf-8"))["response"]["elements"]["elements"]
    r2 = {e["element_identifier"]: e["text"].strip() for e in r2 if e["element_type"] == "requirement"}
    if len(r2) != 110:
        sys.exit(f"Expected 110 Rev. 2 requirements, found {len(r2)}")

    cat = json.load(open(sys.argv[2], encoding="utf-8"))["catalog"]
    r3 = {}
    for g in cat["groups"]:
        for c in g.get("controls", []):
            sid = next((p["value"] for p in c.get("props", []) if p["name"] == "sort-id"), None)
            withdrawn = any(p["name"] == "status" and p.get("value") == "withdrawn" for p in c.get("props", []))
            if sid and not withdrawn:
                r3[sid] = c["title"].strip()

    def obj(d):
        keys = sorted(d, key=lambda k: [int(x) for x in k.split(".")])
        return "{\n" + "".join(f"  {json.dumps(k)}: {json.dumps(d[k], ensure_ascii=False)},\n" for k in keys) + "}"

    out = f"""/**
 * NIST SP 800-171 requirement text (Rev. 2) and titles (Rev. 3), U.S. government
 * works in the public domain. Generated by scripts/nist171-import.py from NIST's
 * CPRT export (Rev. 2) and OSCAL catalog ({cat["metadata"].get("version", "")}, Rev. 3). Do not edit by hand.
 */

export const nist171r2Text: Record<string, string> = {obj(r2)};

export const nist171r3Titles: Record<string, string> = {obj(r3)};
"""
    with open(os.path.join(ROOT, "src", "content", "nist171.ts"), "w", encoding="utf-8") as f:
        f.write(out)
    print(f"Rev. 2: {len(r2)} requirements, Rev. 3: {len(r3)} requirements -> src/content/nist171.ts")


if __name__ == "__main__":
    main()
